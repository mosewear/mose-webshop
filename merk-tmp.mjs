import { chromium, devices } from '@playwright/test'
const b = await chromium.launch()
const ctx = await b.newContext({ ...devices['iPhone 14'], locale: 'nl-NL' })
await ctx.addInitScript(() => { try { localStorage.setItem('mose_cookie_consent', 'all') } catch {} })
const p = await ctx.newPage()
await p.goto('https://www.mosewear.com/nl', { waitUntil: 'domcontentloaded', timeout: 90000 })
await p.waitForTimeout(7000)
await p.locator('[aria-label*="enu" i]').first().click()
await p.waitForTimeout(2500)
await p.screenshot({ path: '/tmp/merk-boven.png' })
const sc = await p.evaluateHandle(() => document.querySelector('[data-mobile-menu] [class*="overflow-y"]'))
await p.evaluate(el => { el.scrollTop = el.scrollHeight }, sc)
await p.waitForTimeout(900)
await p.screenshot({ path: '/tmp/merk-onder.png' })
await b.close()
